#!/usr/bin/env python3
"""Inject SEO metadata into the HonKit-built user manuals and regenerate sitemap.xml.

The manuals in `docs/` (Chinese) and `en/docs/` (English) are generated by HonKit,
so any metadata added by hand is wiped on the next build. Run this script right
after a build; it is idempotent and only touches the marked block it owns.

What it does, per page:
  - real `<meta name="description">` extracted from the first body paragraph
  - `<link rel="canonical">`, Open Graph / Twitter card tags
  - `hreflang` alternates between the Chinese and English page of the same path
  - JSON-LD `TechArticle` + `BreadcrumbList`
  - `<meta name="robots" content="index,follow,max-image-preview:large">`
  - the Cloudflare Web Analytics beacon, when `analytics.cloudflare_token` is set

The beacon also goes into the hand-written landing pages, which are not
rebuilt by HonKit and therefore need their own marked block.

It also writes `sitemap.xml` for the whole site: the static landing pages plus
every manual page, with `xhtml:link` alternates for the bilingual pairs.

Usage:
    python scripts/seo.py                      # use base_url from <site>/seo.json
    python scripts/seo.py --base https://example.com/subpath
    python scripts/seo.py --check              # report without writing
    python scripts/seo.py --site . --config ../seo.json  # config outside the site root
"""

from __future__ import annotations

import argparse
import html
import json
import re
import sys
from datetime import date
from pathlib import Path
from urllib.parse import quote, urlparse

MARK_START = "<!-- seo:start -->"
MARK_END = "<!-- seo:end -->"

# The analytics beacon lives in its own marked block: HonKit regenerates the
# manual pages on every build, and the landing pages are hand-written, so both
# need an idempotent slot that a plain `seo.py` run can fill or empty.
ANALYTICS_START = "<!-- analytics:start -->"
ANALYTICS_END = "<!-- analytics:end -->"

# Static pages at the site root, in sitemap order: (path, changefreq, priority)
STATIC_PAGES = [
    ("", "weekly", "1.0"),
    ("en/", "weekly", "0.8"),
    ("v1/", "yearly", "0.3"),
    ("v1/en/", "yearly", "0.3"),
    ("privacy.html", "yearly", "0.2"),
    ("terms.html", "yearly", "0.2"),
]

# Hand-written pages carry absolute URLs in their head tags, so they cannot be
# regenerated the way manual pages are. Instead every occurrence of a known
# historical base is rewritten to the current one — switching domains then means
# editing `base_url` in seo.json only. Add a line here when the base changes again.
LEGACY_BASES = [
    "https://backlog.kuwork.cn",
    "https://kuwork.github.io/Backlog.md",
]

# Root-level files outside STATIC_PAGES that still embed absolute URLs.
EXTRA_STATIC_FILES = ["robots.txt", "404.html", "mobile.html"]

SECTION_RE = re.compile(r'<section class="normal markdown-section">(.*?)</section>', re.S)
TITLE_RE = re.compile(r"<title>(.*?)</title>", re.S)
DESC_RE = re.compile(r'<meta\s+name="description"\s+content="[^"]*"\s*/?>')
H1_RE = re.compile(r"<h1[^>]*>(.*?)</h1>", re.S)
P_RE = re.compile(r"<p[^>]*>(.*?)</p>", re.S)
TAG_RE = re.compile(r"<[^>]+>")
WS_RE = re.compile(r"\s+")
NUM_PREFIX_RE = re.compile(r"^\d+[-_.\s]*")

BROKEN_DESC = re.compile(r'<meta\s+name="description"\s+content=""\s*/?>')


def clean(text: str) -> str:
    """Strip tags/entities and collapse whitespace."""
    text = TAG_RE.sub(" ", text)
    text = html.unescape(text)
    return WS_RE.sub(" ", text).strip()


def analytics_tag(token: str) -> str:
    """Cloudflare Web Analytics beacon.

    Kept on one line so it can be folded into the indented SEO block of a
    generated page without breaking its formatting.
    """
    payload = json.dumps({"token": token}, separators=(",", ":"))
    return (
        '<script defer src="https://static.cloudflareinsights.com/beacon.min.js"'
        f" data-cf-beacon='{payload}'></script>"
    )


def truncate(text: str, limit: int = 158) -> str:
    if len(text) <= limit:
        return text
    cut = text[:limit]
    # prefer breaking on a sentence boundary
    for sep in ("。", "；", ". ", "，", ", "):
        idx = cut.rfind(sep)
        if idx >= limit * 0.6:
            return cut[: idx + len(sep)].rstrip()
    return cut.rstrip() + "…"


def extract_description(body: str, title: str, fallback: str = "") -> str:
    """Best first paragraph of the page body, else the book-level fallback.

    Imperative one-liners such as "执行以下命令…：" make poor meta descriptions,
    so prefer the first substantive paragraph and only then the longest candidate.
    """
    candidates = []
    for raw in P_RE.findall(body):
        text = clean(raw)
        if not text or text.startswith(("上一页", "下一页", "Previous", "Next")):
            continue
        candidates.append(text)
        if len(candidates) >= 3:
            break

    for text in candidates:
        if len(text) >= 40 and not text.endswith(("：", ":")):
            return truncate(text)
    for text in sorted(candidates, key=len, reverse=True):
        if len(text) >= 20:
            return truncate(text)
    return truncate(fallback or clean(title))


def page_title(doc: str) -> str:
    m = TITLE_RE.search(doc)
    if not m:
        return ""
    # HonKit emits "Page · Backlog.md 用户手册"; keep only the page part
    return clean(m.group(1).split("·")[0])


def pretty_segment(segment: str) -> str:
    """'00-快速开始' -> '快速开始'."""
    return NUM_PREFIX_RE.sub("", segment).strip() or segment


class Site:
    def __init__(self, root: Path, base: str, config: dict):
        self.root = root
        self.base = base.rstrip("/")
        self.config = config
        self.books: list[dict] = config["books"]
        self.analytics_token: str = (config.get("analytics") or {}).get(
            "cloudflare_token", ""
        ).strip()
        # lang -> {relative path (posix, no leading docs dir) : file path}
        self.index: dict[str, dict[str, Path]] = {}

    # ---- paths -----------------------------------------------------------
    def url_for(self, book: dict, rel: str) -> str:
        """Public URL of a manual page. `index.html` collapses to its directory."""
        prefix = book["dir"].strip("/")
        if rel == "index.html":
            path = f"{prefix}/"
        elif rel.endswith("/index.html"):
            path = f"{prefix}/{rel[: -len('index.html')]}"
        else:
            path = f"{prefix}/{rel}"
        return f"{self.base}/{quote(path, safe='/:')}"

    def rel_key(self, book: dict, path: Path) -> str:
        return path.relative_to(self.root / book["dir"]).as_posix()

    def other_book(self, book: dict) -> dict | None:
        for candidate in self.books:
            if candidate is not book and candidate.get("pair") == book.get("pair"):
                return candidate
        return None

    # ---- build index -----------------------------------------------------
    def build_index(self) -> None:
        for book in self.books:
            files: dict[str, Path] = {}
            base_dir = self.root / book["dir"]
            for path in sorted(base_dir.rglob("*.html")):
                files[self.rel_key(book, path)] = path
            self.index[book["dir"]] = files

    # ---- per page --------------------------------------------------------
    def alternates(self, book: dict, rel: str) -> list[tuple[str, str]]:
        """[(hreflang, url)] for this page, including its counterpart."""
        out = [(book["lang"], self.url_for(book, rel))]
        twin = self.other_book(book)
        if twin and rel in self.index.get(twin["dir"], {}):
            out.append((twin["lang"], self.url_for(twin, rel)))
        if len(out) > 1:
            zh = next((u for lang, u in out if lang.startswith("zh")), out[0][1])
            out.append(("x-default", zh))
        return out

    def breadcrumb(self, book: dict, rel: str) -> list[tuple[str, str]]:
        """Breadcrumb trail built from real pages only.

        HonKit emits no `index.html` for a chapter folder (e.g. `00-快速开始/`),
        so an intermediate directory that has no page is skipped instead of
        pointing at a URL that 404s.
        """
        files = self.index.get(book["dir"], {})
        crumbs = [(book["label"], f"{self.base}/{book['dir'].strip('/')}/")]
        acc: list[str] = []
        for part in Path(rel).parts:
            acc.append(part)
            sub = "/".join(acc)
            if sub == "index.html":
                break  # the book root itself, already seeded
            if sub.endswith("index.html"):
                page = sub
                label = pretty_segment(Path(sub).parent.name)
            else:
                page = sub
                label = pretty_segment(part[:-5] if part.endswith(".html") else part)
            if page in files:
                crumbs.append((label, self.url_for(book, page)))
            elif f"{page}/index.html" in files:
                crumbs.append((label, self.url_for(book, f"{page}/index.html")))
            # directory without its own page: no breadcrumb entry
        return crumbs

    def block(self, book: dict, rel: str, path: Path) -> str:
        doc = path.read_text(encoding="utf-8")
        body_m = SECTION_RE.search(doc)
        body = body_m.group(1) if body_m else ""
        title = page_title(doc) or pretty_segment(rel)
        desc = extract_description(body, title, book.get("book_description", ""))
        if rel == "index.html" and book.get("book_description"):
            desc = truncate(book["book_description"])
        canonical = self.url_for(book, rel)
        alts = self.alternates(book, rel)
        crumbs = self.breadcrumb(book, rel)

        og_image = f"{self.base}/assets/img/og-image.jpg"
        lines = [
            MARK_START,
            f'<meta name="robots" content="index,follow,max-image-preview:large" />',
            f'<meta name="description" content="{html.escape(desc, quote=True)}" />',
            f'<link rel="canonical" href="{canonical}" />',
        ]
        for lang, url in alts:
            lines.append(f'<link rel="alternate" hreflang="{lang}" href="{url}" />')
        lines += [
            '<meta property="og:type" content="article" />',
            f'<meta property="og:site_name" content="{html.escape(book["brand"])}" />',
            f'<meta property="og:locale" content="{book["og_locale"]}" />',
            f'<meta property="og:title" content="{html.escape(title, quote=True)}" />',
            f'<meta property="og:description" content="{html.escape(desc, quote=True)}" />',
            f'<meta property="og:url" content="{canonical}" />',
            f'<meta property="og:image" content="{og_image}" />',
            '<meta name="twitter:card" content="summary_large_image" />',
            f'<meta name="twitter:title" content="{html.escape(title, quote=True)}" />',
            f'<meta name="twitter:description" content="{html.escape(desc, quote=True)}" />',
            f'<meta name="twitter:image" content="{og_image}" />',
        ]
        if self.analytics_token:
            lines.append(analytics_tag(self.analytics_token))

        article = {
            "@context": "https://schema.org",
            "@type": "TechArticle",
            "headline": title,
            "description": desc,
            "inLanguage": book["lang"],
            "url": canonical,
            "mainEntityOfPage": canonical,
            "isPartOf": {
                "@type": "Book",
                "name": book["book_name"],
                "url": f"{self.base}/{book['dir'].strip('/')}/",
            },
            "publisher": {
                "@type": "Organization",
                "name": book["brand"],
                "url": f"{self.base}/",
            },
        }
        crumbs_ld = {
            "@context": "https://schema.org",
            "@type": "BreadcrumbList",
            "itemListElement": [
                {"@type": "ListItem", "position": i + 1, "name": name, "item": url}
                for i, (name, url) in enumerate(crumbs)
            ],
        }
        payloads = [article]
        if len(crumbs) > 1:  # a single-item trail carries no information
            payloads.append(crumbs_ld)
        for payload in payloads:
            lines.append(
                '<script type="application/ld+json">'
                + json.dumps(payload, ensure_ascii=False, separators=(",", ":"))
                + "</script>"
            )
        lines.append(MARK_END)
        return "\n        ".join(lines)

    def inject(self, book: dict, rel: str, path: Path, write: bool) -> bool:
        doc = path.read_text(encoding="utf-8")
        block = self.block(book, rel, path)
        new = doc
        if MARK_START in doc:
            new = re.sub(
                re.escape(MARK_START) + r".*?" + re.escape(MARK_END),
                lambda _m: block,
                doc,
                count=1,
                flags=re.S,
            )
        else:
            anchor = None
            m = DESC_RE.search(doc)
            if m:
                anchor = m.group(0)
                new = doc[: m.start()] + block + doc[m.end() :]
            else:
                m = TITLE_RE.search(doc)
                if not m:
                    return False
                insert_at = doc.find("</title>") + len("</title>")
                new = doc[:insert_at] + "\n        " + block + doc[insert_at:]
            # drop HonKit's empty description meta if it survived (no anchor case)
            if anchor is None:
                new = BROKEN_DESC.sub("", new)
        if write and new != doc:
            path.write_text(new, encoding="utf-8")
        return new != doc

    # ---- static pages ----------------------------------------------------
    def static_page_files(self) -> list[str]:
        """The hand-written landing pages, as site-relative paths."""
        out = []
        for path, _freq, _prio in STATIC_PAGES:
            if not path:
                out.append("index.html")
            elif path.endswith("/"):
                out.append(path + "index.html")
            else:
                out.append(path)
        return [p for p in out if (self.root / p).is_file()]

    def static_files(self) -> list[str]:
        """Files whose absolute URLs need to track `base`."""
        return self.static_page_files() + [
            p for p in EXTRA_STATIC_FILES if (self.root / p).is_file()
        ]

    def sync_static(self, write: bool) -> list[str]:
        """Rewrite legacy absolute URLs in the hand-written pages to `base`."""
        changed: list[str] = []
        # longest first, so a base that is a prefix of another cannot shadow it
        bases = sorted(set(LEGACY_BASES) - {self.base}, key=len, reverse=True)
        for rel in self.static_files():
            path = self.root / rel
            doc = path.read_text(encoding="utf-8")
            new = doc
            for old in bases:
                new = new.replace(old, self.base)
            if new != doc:
                if write:
                    path.write_text(new, encoding="utf-8")
                changed.append(rel)
        return changed

    def sync_analytics(self, write: bool) -> list[str]:
        """Keep the analytics beacon in the hand-written pages.

        Manual pages pick it up from the SEO block, but these are edited by
        hand and never rebuilt, so they carry their own marked block. Clearing
        the token removes the block again: opting out has to be as reachable as
        opting in.
        """
        body = ""
        if self.analytics_token:
            tag = analytics_tag(self.analytics_token)
            body = f"{ANALYTICS_START}\n\t\t{tag}\n\t\t{ANALYTICS_END}"
        changed: list[str] = []
        marked = (
            r"\n[ \t]*"
            + re.escape(ANALYTICS_START)
            + r".*?"
            + re.escape(ANALYTICS_END)
        )
        for rel in self.static_page_files():
            path = self.root / rel
            doc = path.read_text(encoding="utf-8")
            if ANALYTICS_START in doc:
                repl = f"\n\t\t{body}" if body else ""
                new = re.sub(marked, lambda _m: repl, doc, count=1, flags=re.S)
            elif body and "</head>" in doc:
                new = re.sub(
                    r"\n[ \t]*</head>",
                    lambda _m: f"\n\t\t{body}\n\t</head>",
                    doc,
                    count=1,
                )
            else:
                continue
            if new != doc:
                if write:
                    path.write_text(new, encoding="utf-8")
                changed.append(rel)
        return changed

    def sync_root_paths(self, write: bool) -> list[str]:
        """Give `404.html` the deployment sub-path.

        A 404 page is served at whatever depth the missing URL had, so its own
        links must be root-absolute — which under a project page means carrying
        the `/Backlog.md` prefix. Prefixes are normalised first, so this stays
        idempotent when the base changes.
        """
        prefix = urlparse(self.base).path.rstrip("/")
        if not prefix:
            return []  # deployed at the domain root: `/assets/...` is already right
        path = self.root / "404.html"
        if not path.is_file():
            return []
        doc = path.read_text(encoding="utf-8")
        new = doc.replace(f'"{prefix}/', '"/')
        new = re.sub(r'(href|src)="/(?!/)', lambda m: f'{m.group(1)}="{prefix}/', new)
        if new == doc:
            return []
        if write:
            path.write_text(new, encoding="utf-8")
        return ["404.html"]

    # ---- sitemap ---------------------------------------------------------
    def sitemap(self) -> str:
        today = date.today().isoformat()
        rows: list[str] = []
        for path, freq, prio in STATIC_PAGES:
            rows.append(
                "  <url>\n"
                f"    <loc>{self.base}/{path}</loc>\n"
                f"    <lastmod>{today}</lastmod>\n"
                f"    <changefreq>{freq}</changefreq>\n"
                f"    <priority>{prio}</priority>\n"
                "  </url>"
            )
        for book in self.books:
            for rel, path in self.index[book["dir"]].items():
                if rel == "404.html":
                    continue
                alts = self.alternates(book, rel)
                alt_xml = "".join(
                    f'\n    <xhtml:link rel="alternate" hreflang="{lang}" href="{url}" />'
                    for lang, url in alts
                )
                prio = "0.7" if rel == "index.html" else "0.6"
                rows.append(
                    "  <url>\n"
                    f"    <loc>{self.url_for(book, rel)}</loc>\n"
                    f"    <lastmod>{today}</lastmod>\n"
                    "    <changefreq>monthly</changefreq>\n"
                    f"    <priority>{prio}</priority>{alt_xml}\n"
                    "  </url>"
                )
        return (
            '<?xml version="1.0" encoding="UTF-8"?>\n'
            '<urlset xmlns="http://www.sitemaps.org/schemas/sitemap/0.9"\n'
            '        xmlns:xhtml="http://www.w3.org/1999/xhtml">\n'
            + "\n".join(rows)
            + "\n</urlset>\n"
        )


def main() -> int:
    ap = argparse.ArgumentParser(description="Inject SEO metadata into HonKit manuals and rebuild sitemap.xml")
    ap.add_argument("--site", default=".", help="Static site root (default: cwd)")
    ap.add_argument("--config", default=None, help="Path to seo.json (default: <site>/seo.json)")
    ap.add_argument("--base", default=None, help="Canonical base URL; overrides seo.json")
    ap.add_argument("--check", action="store_true", help="Report pages needing updates without writing")
    ap.add_argument("--no-sitemap", action="store_true", help="Skip sitemap.xml generation")
    args = ap.parse_args()

    root = Path(args.site).resolve()
    config_path = Path(args.config).resolve() if args.config else root / "seo.json"
    if not config_path.exists():
        print(f"error: missing {config_path}", file=sys.stderr)
        return 2
    config = json.loads(config_path.read_text(encoding="utf-8"))
    base = args.base or config["base_url"]

    site = Site(root, base, config)
    site.build_index()

    changed = 0
    total = 0
    for book in site.books:
        for rel, path in site.index[book["dir"]].items():
            if rel == "404.html":
                continue
            total += 1
            if site.inject(book, rel, path, write=not args.check):
                changed += 1

    print(f"base: {site.base}")
    for book in site.books:
        count = len(site.index[book["dir"]])
        print(f"  {book['dir']:<10} {count:>3} pages  ({book['lang']})")
    verb = "would update" if args.check else "updated"
    print(f"{verb}: {changed}/{total} pages")

    static_changed = site.sync_static(write=not args.check)
    if static_changed:
        print(f"static pages: {verb} {', '.join(static_changed)}")
    else:
        print("static pages: already on the current base")

    analytics_changed = site.sync_analytics(write=not args.check)
    if analytics_changed:
        print(f"analytics: {verb} {', '.join(analytics_changed)}")
    elif not site.analytics_token:
        print("analytics: no token, beacon not injected")
    else:
        print("analytics: already in place on every hand-written page")

    root_changed = site.sync_root_paths(write=not args.check)
    if root_changed:
        print(f"404 paths: {verb} {', '.join(root_changed)}")

    if not args.no_sitemap:
        sitemap = site.sitemap()
        target = root / "sitemap.xml"
        if args.check:
            print("sitemap: not written (--check)")
        else:
            target.write_text(sitemap, encoding="utf-8")
            urls = sitemap.count("<loc>")
            print(f"sitemap.xml: {urls} urls")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
