#!/usr/bin/env bun
/**
 * Build-time script that embeds bundled agent skills into TypeScript modules
 * so they are available in the compiled binary.
 *
 * Each skill produces two exports in its generated module:
 * - `<NAME>_SKILL`: skill content files, always (re)written on install.
 * - `<NAME>_SEED_FILES`: project-owned memory files. The template content is
 *   embedded under the target path and written only when the target file does
 *   not exist yet — never overwritten, even with --force.
 *
 * Seed templates and their (locally maintained) targets are excluded from
 * `<NAME>_SKILL` so private project memory never ends up in the binary.
 */
import { readdir, readFile } from "node:fs/promises";
import { join, relative } from "node:path";

interface SeedFileMapping {
	/** Template file inside the skill directory, embedded as the seed content. */
	template: string;
	/** Path the seed is installed to (and the local memory file excluded from embedding). */
	target: string;
}

interface SkillEmbedConfig {
	name: string;
	exportName: string;
	seedExportName: string;
	seedFiles: SeedFileMapping[];
}

const SKILLS_DIR = join(import.meta.dir, "..", ".codex", "skills");
const OUTPUT_DIR = join(import.meta.dir, "..", "src", "skills", "embedded");

const SKILLS: SkillEmbedConfig[] = [
	{
		name: "llm-wiki-for-backlog",
		exportName: "LLM_WIKI_FOR_BACKLOG_SKILL",
		seedExportName: "LLM_WIKI_FOR_BACKLOG_SEED_FILES",
		seedFiles: [],
	},
	{
		name: "task-migration-architect",
		exportName: "TASK_MIGRATION_ARCHITECT_SKILL",
		seedExportName: "TASK_MIGRATION_ARCHITECT_SEED_FILES",
		seedFiles: [
			{
				template: "references/current-branch-migration-exclusions.template.md",
				target: "references/current-branch-migration-exclusions.md",
			},
		],
	},
];

async function collectFiles(dir: string, baseDir: string, exclude: Set<string>): Promise<Record<string, string>> {
	const result: Record<string, string> = {};
	const entries = await readdir(dir, { withFileTypes: true });

	for (const entry of entries) {
		const fullPath = join(dir, entry.name);
		const relPath = relative(baseDir, fullPath).replace(/\\/g, "/");

		if (entry.isDirectory()) {
			const nested = await collectFiles(fullPath, baseDir, exclude);
			Object.assign(result, nested);
		} else if (!exclude.has(relPath)) {
			const content = await readFile(fullPath, "utf-8");
			result[relPath] = content;
		}
	}

	return result;
}

function escapeContent(content: string): string {
	return content.replace(/\\/g, "\\\\").replace(/`/g, "\\`").replace(/\${/g, "\\${");
}

function renderRecord(files: Record<string, string>): string {
	return Object.entries(files)
		.map(([path, content]) => `\t"${path}": \`${escapeContent(content)}\`,`)
		.join("\n");
}

async function embedSkill(config: SkillEmbedConfig): Promise<void> {
	const skillDir = join(SKILLS_DIR, config.name);
	const exclude = new Set<string>();
	for (const seed of config.seedFiles) {
		exclude.add(seed.template);
		exclude.add(seed.target);
	}

	const files = await collectFiles(skillDir, skillDir, exclude);

	const seedFiles: Record<string, string> = {};
	for (const seed of config.seedFiles) {
		seedFiles[seed.target] = await readFile(join(skillDir, seed.template), "utf-8");
	}

	const output = `// AUTO-GENERATED by scripts/embed-skills.ts
// Do not edit manually. Run \`bun scripts/embed-skills.ts\` to regenerate.

export const ${config.exportName}: Record<string, string> = {
${renderRecord(files)}
};

export const ${config.seedExportName}: Record<string, string> = {
${renderRecord(seedFiles)}
};
`;

	const outputFile = join(OUTPUT_DIR, `${config.name}.ts`);
	await Bun.write(outputFile, output);
	console.log(
		`Embedded ${Object.keys(files).length} files (+${Object.keys(seedFiles).length} seed files) from ${config.name} into ${outputFile}`,
	);
}

async function main(): Promise<void> {
	for (const skill of SKILLS) {
		await embedSkill(skill);
	}
}

main().catch((err) => {
	console.error("Failed to embed skills:", err);
	process.exit(1);
});
